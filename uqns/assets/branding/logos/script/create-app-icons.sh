#!/usr/bin/env bash

set -Eeuo pipefail

###############################################################################
# QURAN NAVIGATION
# APP ICON GENERATOR
###############################################################################

SOURCE="logos/icon/icon-color.png"

OUTPUT_DIR="logos/app-icons"

mkdir -p "$OUTPUT_DIR"

###############################################################################
# DEPENDENCY CHECK
###############################################################################

command -v convert >/dev/null 2>&1 || {
    echo "ERROR: ImageMagick is not installed."
    exit 1
}

###############################################################################
# VALIDATION
###############################################################################

if [ ! -f "$SOURCE" ]; then
    echo
    echo "ERROR:"
    echo "Source icon not found:"
    echo "$SOURCE"
    echo
    exit 1
fi

###############################################################################
# BANNER
###############################################################################

echo
echo "========================================"
echo " APP ICON GENERATOR SYSTEM"
echo "========================================"
echo

###############################################################################
# GENERATOR FUNCTION
###############################################################################

generate_icon() {

    local SIZE="$1"
    local FILE="$2"

    echo "Creating $FILE"

    convert "$SOURCE" \
        -background none \
        -gravity center \
        -resize "${SIZE}x${SIZE}" \
        -extent "${SIZE}x${SIZE}" \
        -strip \
        PNG32:"${OUTPUT_DIR}/${FILE}"
}

###############################################################################
# ANDROID
###############################################################################

generate_icon 192 android-icon-192.png
generate_icon 512 android-icon-512.png

###############################################################################
# GENERIC APP
###############################################################################

generate_icon 128 app-icon-128.png
generate_icon 256 app-icon-256.png
generate_icon 512 app-icon-512.png

###############################################################################
# IOS
###############################################################################

generate_icon 180 ios-icon-180.png

###############################################################################
# WINDOWS
###############################################################################

generate_icon 256 windows-icon-256.png

###############################################################################
# VERIFICATION
###############################################################################

echo
echo "========================================"
echo " GENERATED APP ICONS"
echo "========================================"
echo

ls -lh "$OUTPUT_DIR"

echo
echo "Verification:"
echo

for FILE in "$OUTPUT_DIR"/*.png
do
    identify "$FILE"
done

echo
echo "========================================"
echo " SUCCESS"
echo "========================================"
echo
