#!/usr/bin/env bash

set -Eeuo pipefail

###############################################################################
# QURAN NAVIGATION
# FAVICON.ICO GENERATOR
###############################################################################

SOURCE="logos/icon/icon-color.png"

OUTPUT="logos/favicon.ico"

###############################################################################
# DEPENDENCY CHECK
###############################################################################

command -v convert >/dev/null 2>&1 || {
    echo "ERROR: ImageMagick is not installed."
    exit 1
}

###############################################################################
# VALIDATION
###############################################################################

if [ ! -f "$SOURCE" ]; then
    echo
    echo "ERROR:"
    echo "Source icon not found:"
    echo "$SOURCE"
    echo
    exit 1
fi

###############################################################################
# BANNER
###############################################################################

echo
echo "========================================"
echo " FAVICON.ICO GENERATOR"
echo "========================================"
echo

###############################################################################
# CREATE MULTI-SIZE ICO
###############################################################################

echo "Creating favicon.ico ..."

convert "$SOURCE" \
    $$ -clone 0 -resize 16x16 $$ \
    $$ -clone 0 -resize 32x32 $$ \
    $$ -clone 0 -resize 48x48 $$ \
    $$ -clone 0 -resize 64x64 $$ \
    $$ -clone 0 -resize 128x128 $$ \
    $$ -clone 0 -resize 256x256 $$ \
    -delete 0 \
    "$OUTPUT"

###############################################################################
# VERIFY
###############################################################################

echo
echo "Verification:"
echo

file "$OUTPUT"

echo
ls -lh "$OUTPUT"

echo
echo "========================================"
echo " SUCCESS"
echo "========================================"
echo
